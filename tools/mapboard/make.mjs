// Map board data (WP-16): Natural Earth countries (world-atlas, public domain) projected by d3-geo's Natural Earth 1
// projection into SVG paths for the `map` set (sets/map.js).
//
//   node tools/mapboard/make.mjs <name> <110m|50m|10m> <centre longitude> [lon0 lat0 lon1 lat1]
//
// writes sets/maps/<name>.js: window.MAPS[name] = {res, rotate, k, countries: {name: {d, c, b}}, land, grat, box}.
// Coordinates are the projection's own (scale k, no translation, y down), rounded to 0.1. The set re-projects pins,
// routes and boxes with the same formula (MAPS.project), so the two always agree (the `mapboard` test checks it
// against d3-geo). With a box (degrees), only what lies inside it, plus a margin, is kept.
import { geoNaturalEarth1, geoPath, geoGraticule10, geoBounds } from 'd3-geo';
import { feature, mesh } from 'topojson-client';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const [name, res = '110m', lonc = '0', ...bx] = process.argv.slice(2);
if (!name) { console.error('usage: make.mjs <name> <110m|50m|10m> <centre lon> [lon0 lat0 lon1 lat1]'); process.exit(2); }
const K = 300, rot = [-(+lonc), 0];
const topo = JSON.parse(readFileSync(join(here, 'node_modules/world-atlas', `countries-${res}.json`)));
const proj = geoNaturalEarth1().rotate(rot).scale(K).translate([0, 0]).precision(0.1);
let box = null;
if (bx.length === 4) {
  const [l0, a0, l1, a1] = bx.map(Number), m = 12;   // margin in degrees, so a slow pan never shows the cut
  const pts = []; for (let i = 0; i <= 8; i++) for (const a of [a0 - m, a1 + m]) pts.push(proj([l0 - m + (l1 - l0 + 2 * m) * i / 8, a]));
  for (let i = 0; i <= 8; i++) for (const l of [l0 - m, l1 + m]) pts.push(proj([l, a0 - m + (a1 - a0 + 2 * m) * i / 8]));
  const xs = pts.map(p => p[0]), ys = pts.map(p => p[1]);
  box = [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)];
  proj.clipExtent([[box[0], box[1]], [box[2], box[3]]]);
}
const path = geoPath(proj).digits(1);
const r1 = v => Math.round(v * 10) / 10;
const countries = {};
for (const f of feature(topo, topo.objects.countries).features) {
  const d = path(f); if (!d) continue;
  const b = path.bounds(f), c = path.centroid(f);
  if (!isFinite(b[0][0])) continue;
  const nm = f.properties.name;
  countries[nm] = { d, c: c.map(r1), b: [b[0][0], b[0][1], b[1][0], b[1][1]].map(r1), ll: geoBounds(f).flat().map(r1) };
}
const land = path(mesh(topo, topo.objects.countries, (a, b) => a === b));   // coastlines (outer edges only)
const borders = path(mesh(topo, topo.objects.countries, (a, b) => a !== b));
const grat = path(geoGraticule10());
const sphere = path({ type: 'Sphere' });
const out = { name, res, rotate: rot, k: K, box: box && box.map(r1), countries, coast: land, borders, grat, sphere,
  source: `Natural Earth via world-atlas@2.0.2 countries-${res} (public domain), projected with d3-geo@3.1.1 geoNaturalEarth1` };
const file = join(here, '..', '..', 'sets', 'maps', `${name}.js`);
mkdirSync(dirname(file), { recursive: true });
writeFileSync(file, `// generated by tools/mapboard/make.mjs ${process.argv.slice(2).join(' ')}: do not edit\n` +
  `(function (root) { (root.MAPS = root.MAPS || {})[${JSON.stringify(name)}] = ${JSON.stringify(out)}; })(typeof window !== 'undefined' ? window : globalThis);\n`);
console.log(JSON.stringify({ file, countries: Object.keys(countries).length, bytes: readFileSync(file).length, box }));
