"""Project Natural Earth TopoJSON (world-atlas, us-atlas; public domain) into
SVG path strings for a film's map shots.

    python tools/mapgen.py COUNTRIES_50M STATES_10M OUT_JS

Writes `window.MAP = {w, h, lon0, lon1, lat0, lat1, countries: {name: d}, states: {name: d}}`
in a Mercator projection fitted to the frame; a JS helper `MAP.xy(lon, lat)` re-projects points.
"""
import json
import math
import sys

LON0, LON1, LAT0, LAT1 = -125.5, -73.0, 5.5, 50.5
W = 1000.0  # map width in px; height follows from the projection


def merc(lat):
    return math.log(math.tan(math.pi / 4 + math.radians(lat) / 2))


SX = W / (LON1 - LON0)
Y0, Y1 = merc(LAT1), merc(LAT0)
H = (Y1 - Y0) / math.radians(1) * SX * -1  # positive height
KY = H / (Y0 - Y1)


def xy(lon, lat):
    return ((lon - LON0) * SX, (Y0 - merc(max(-80, min(80, lat)))) * KY)


def decode_arcs(topo):
    sc, tr = topo['transform']['scale'], topo['transform']['translate']
    out = []
    for arc in topo['arcs']:
        x = y = 0
        pts = []
        for dx, dy in arc:
            x += dx; y += dy
            pts.append((x * sc[0] + tr[0], y * sc[1] + tr[1]))
        out.append(pts)
    return out


def ring(arcs, idx):
    pts = []
    for i in idx:
        a = arcs[i] if i >= 0 else arcs[~i][::-1]
        pts.extend(a if not pts else a[1:])
    return pts


def geom_rings(g):
    if g['type'] == 'Polygon':
        return g['arcs']
    if g['type'] == 'MultiPolygon':
        return [r for poly in g['arcs'] for r in poly]
    return []


def path(rings_pts, tol=1.2):
    d = []
    for pts in rings_pts:
        lons = [p[0] for p in pts]; lats = [p[1] for p in pts]
        if max(lons) < LON0 - 8 or min(lons) > LON1 + 8 or max(lats) < LAT0 - 6 or min(lats) > LAT1 + 6:
            continue
        P = [xy(*p) for p in pts]
        keep = [P[0]]
        for p in P[1:]:
            if math.hypot(p[0] - keep[-1][0], p[1] - keep[-1][1]) >= tol:
                keep.append(p)
        if len(keep) < 3:
            continue
        d.append('M' + 'L'.join(f'{x:.1f} {y:.1f}' for x, y in keep) + 'Z')
    return ''.join(d)


def main():
    cj, sj, out = sys.argv[1:4]
    world = json.load(open(cj)); arcs = decode_arcs(world)
    want = {'United States of America': 'usa', 'Canada': 'canada', 'Mexico': 'mexico', 'Guatemala': 'guatemala',
            'Belize': 'belize', 'Honduras': 'honduras', 'El Salvador': 'salvador', 'Nicaragua': 'nicaragua',
            'Costa Rica': 'costarica', 'Panama': 'panama', 'Colombia': 'colombia', 'Venezuela': 'venezuela',
            'Ecuador': 'ecuador', 'Cuba': 'cuba', 'Bahamas': 'bahamas', 'Jamaica': 'jamaica', 'Haiti': 'haiti',
            'Dominican Rep.': 'dominican'}
    countries = {}
    for g in world['objects']['countries']['geometries']:
        nm = g['properties']['name']
        if nm in want:
            countries[want[nm]] = path([ring(arcs, r) for r in geom_rings(g)])
    us = json.load(open(sj)); arcs2 = decode_arcs(us)
    states = {}
    for g in us['objects']['states']['geometries']:
        nm = g['properties']['name']
        if nm in ('Alaska', 'Hawaii', 'Puerto Rico', 'United States Virgin Islands', 'Guam',
                  'Commonwealth of the Northern Mariana Islands', 'American Samoa'):
            continue
        states[nm] = path([ring(arcs2, r) for r in geom_rings(g)], tol=1.6)
    data = {'w': W, 'h': round(H, 1), 'lon0': LON0, 'lon1': LON1, 'lat0': LAT0, 'lat1': LAT1,
            'countries': countries, 'states': states}
    js = ('// generated by tools/mapgen.py from Natural Earth via world-atlas@2.0.2 and us-atlas@3.0.1 (public domain)\n'
          f'window.MAP = {json.dumps(data, separators=(",", ":"))};\n'
          '(function (m) {\n'
          '  const merc = lat => Math.log(Math.tan(Math.PI / 4 + lat * Math.PI / 360));\n'
          '  const sx = m.w / (m.lon1 - m.lon0), y0 = merc(m.lat1), ky = m.h / (y0 - merc(m.lat0));\n'
          '  m.xy = (lon, lat) => [(lon - m.lon0) * sx, (y0 - merc(lat)) * ky];\n'
          '})(window.MAP);\n')
    open(out, 'w').write(js)
    print(f'map {W:.0f}x{H:.0f}, {len(countries)} countries, {len(states)} states, {len(js)//1024} KB')


if __name__ == '__main__':
    main()
